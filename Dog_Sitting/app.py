import os
import sqlite3
from contextlib import contextmanager
from datetime import date
from functools import wraps
import hmac

from flask import (
    Flask, render_template, request, redirect,
    url_for, session, flash, abort
)
from werkzeug.security import check_password_hash

# PostgreSQL is used when DATABASE_URL is set.
# Local development can continue using the existing SQLite bookings.db.
DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()
APP_MODE = os.environ.get("APP_MODE", "local").strip().lower()
IS_PUBLIC = APP_MODE == "public"

if IS_PUBLIC and not DATABASE_URL:
    raise RuntimeError("DATABASE_URL must be configured for the public deployment.")

if DATABASE_URL:
    import psycopg
    from psycopg.rows import dict_row

app = Flask(__name__)

# Configure FLASK_SECRET_KEY in Render and locally if you want persistent sessions.
# The fallback is only for local development; never use it in the public deployment.
app.secret_key = os.environ.get("FLASK_SECRET_KEY")
if not app.secret_key:
    if IS_PUBLIC:
        raise RuntimeError("FLASK_SECRET_KEY must be configured for the public deployment.")
    app.secret_key = "local-development-only-change-this-key"

ADMIN_USERNAME = os.environ.get("ADMIN_USERNAME", "bhusted")
ADMIN_PASSWORD_HASH = os.environ.get("ADMIN_PASSWORD_HASH", "")
SQLITE_DATABASE = os.path.join(os.path.dirname(__file__), "bookings.db")

STATUSES = ["Pending", "Approved", "Declined", "Completed", "Canceled"]


@contextmanager
def get_db():
    """Open and close one database connection, committing successful writes."""
    if DATABASE_URL:
        connection = psycopg.connect(DATABASE_URL, row_factory=dict_row)
    else:
        connection = sqlite3.connect(SQLITE_DATABASE)
        connection.row_factory = sqlite3.Row

    try:
        yield connection
        connection.commit()
    except Exception:
        connection.rollback()
        raise
    finally:
        connection.close()


def execute(db, sql, params=()):
    """Use the appropriate parameter placeholders for PostgreSQL or SQLite."""
    if DATABASE_URL:
        sql = sql.replace("?", "%s")
    return db.execute(sql, params)


def init_db():
    with get_db() as db:
        execute(db, """
            CREATE TABLE IF NOT EXISTS bookings (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name TEXT NOT NULL DEFAULT '',
                email TEXT NOT NULL DEFAULT '',
                phone TEXT DEFAULT '',
                service TEXT NOT NULL DEFAULT '',
                service_date TEXT NOT NULL DEFAULT '',
                service_time TEXT NOT NULL DEFAULT '',
                details TEXT DEFAULT '',
                status TEXT NOT NULL DEFAULT 'Pending',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)

        if DATABASE_URL:
            existing_columns = {
                row["column_name"]
                for row in execute(db, """
                    SELECT column_name
                    FROM information_schema.columns
                    WHERE table_schema = 'public' AND table_name = 'bookings'
                """).fetchall()
            }
        else:
            existing_columns = {
                row["name"]
                for row in execute(db, "PRAGMA table_info(bookings)").fetchall()
            }

        required_columns = {
            "name": "TEXT NOT NULL DEFAULT ''",
            "email": "TEXT NOT NULL DEFAULT ''",
            "phone": "TEXT DEFAULT ''",
            "service": "TEXT NOT NULL DEFAULT ''",
            "service_date": "TEXT NOT NULL DEFAULT ''",
            "service_time": "TEXT NOT NULL DEFAULT ''",
            "details": "TEXT DEFAULT ''",
            "status": "TEXT NOT NULL DEFAULT 'Pending'",
            "created_at": "TIMESTAMP",
        }

        for column, definition in required_columns.items():
            if column not in existing_columns:
                execute(db, f"ALTER TABLE bookings ADD COLUMN {column} {definition}")


@app.before_request
def keep_admin_local():
    # Render must set APP_MODE=public. This makes every /admin URL return 404 there.
    if IS_PUBLIC and (request.path == "/admin" or request.path.startswith("/admin/")):
        abort(404)


def admin_required(view):
    @wraps(view)
    def wrapped_view(**kwargs):
        if not session.get("admin_authenticated"):
            return redirect(url_for("admin_login"))
        return view(**kwargs)
    return wrapped_view


@app.route("/")
def index():
    return render_template("index.html", today=date.today().isoformat())


@app.route("/book", methods=["POST"])
def book():
    name = request.form.get("name", "").strip()
    email = request.form.get("email", "").strip()
    phone = request.form.get("phone", "").strip()
    service = request.form.get("service", "").strip()
    service_date = request.form.get("date", "").strip()
    service_time = request.form.get("time", "").strip()
    details = request.form.get("details", "").strip()

    if not all([name, email, service, service_date, service_time]):
        flash("Please fill in all required fields.", "error")
        return redirect(url_for("index"))

    try:
        requested_date = date.fromisoformat(service_date)
    except ValueError:
        flash("Please enter a valid date.", "error")
        return redirect(url_for("index"))

    if requested_date < date.today():
        flash("Please choose today or a future date.", "error")
        return redirect(url_for("index"))

    with get_db() as db:
        execute(db, """
            INSERT INTO bookings (
                name, email, phone, service, service_date, service_time,
                details, status, created_at
            )
            VALUES (?, ?, ?, ?, ?, ?, ?, 'Pending', CURRENT_TIMESTAMP)
        """, (
            name, email, phone, service, service_date, service_time, details
        ))

    return render_template("confirmation.html", name=name)


@app.route("/admin/login", methods=["GET", "POST"])
def admin_login():
    if request.method == "POST":
        username = request.form.get("username", "")
        password = request.form.get("password", "")

        if (
            ADMIN_PASSWORD_HASH
            and hmac.compare_digest(username, ADMIN_USERNAME)
            and check_password_hash(ADMIN_PASSWORD_HASH, password)
        ):
            session.clear()
            session["admin_authenticated"] = True
            return redirect(url_for("admin_dashboard"))

        flash("Invalid username or password.", "error")

    return render_template("admin_login.html")


@app.route("/admin/logout", methods=["POST"])
@admin_required
def admin_logout():
    session.clear()
    return redirect(url_for("admin_login"))


@app.route("/admin")
@admin_required
def admin_dashboard():
    selected_status = request.args.get("status", "All")

    with get_db() as db:
        counts = {
            row["status"]: row["total"]
            for row in execute(db, """
                SELECT status, COUNT(*) AS total
                FROM bookings
                GROUP BY status
            """).fetchall()
        }

        if selected_status in STATUSES:
            bookings = execute(db, """
                SELECT * FROM bookings
                WHERE status = ?
                ORDER BY service_date ASC, service_time ASC
            """, (selected_status,)).fetchall()
        else:
            selected_status = "All"
            bookings = execute(db, """
                SELECT * FROM bookings
                ORDER BY
                    CASE status
                        WHEN 'Pending' THEN 0
                        WHEN 'Approved' THEN 1
                        ELSE 2
                    END,
                    service_date ASC,
                    service_time ASC
            """).fetchall()

    return render_template(
        "admin_dashboard.html",
        bookings=bookings,
        statuses=STATUSES,
        selected_status=selected_status,
        counts=counts
    )


@app.route("/admin/bookings/<int:booking_id>/status", methods=["POST"])
@admin_required
def update_booking_status(booking_id):
    new_status = request.form.get("status", "")

    if new_status not in STATUSES:
        abort(400, "Invalid booking status.")

    with get_db() as db:
        result = execute(db, """
            UPDATE bookings
            SET status = ?
            WHERE id = ?
        """, (new_status, booking_id))

        if result.rowcount == 0:
            abort(404, "Booking not found.")

    flash(f"Booking #{booking_id} updated to {new_status}.", "success")
    return redirect(url_for(
        "admin_dashboard",
        status=request.form.get("return_status", "All")
    ))


@app.route("/admin/bookings/<int:booking_id>/delete", methods=["POST"])
@admin_required
def delete_booking(booking_id):
    return_status = request.form.get("return_status", "All")

    if return_status not in ["All"] + STATUSES:
        return_status = "All"

    with get_db() as db:
        booking = execute(db, """
            SELECT status FROM bookings WHERE id = ?
        """, (booking_id,)).fetchone()

        if booking is None:
            flash("Booking not found.", "error")
        elif booking["status"] != "Completed":
            flash("Only completed bookings can be removed.", "error")
        else:
            execute(db, "DELETE FROM bookings WHERE id = ?", (booking_id,))
            flash("Completed booking removed.", "success")

    return redirect(url_for("admin_dashboard", status=return_status))


# Initialize the configured database when the app starts.
init_db()


if __name__ == "__main__":
    # Local development only. Render runs Gunicorn instead.
    app.run(debug=(not IS_PUBLIC))
